// 1-indexed question numbers for each affect scale
const PA_ITEMS = [1, 3, 5, 9, 10, 12, 14, 16, 17, 19];
const NA_ITEMS = [2, 4, 6, 7, 8, 11, 13, 15, 18, 20];

export type PanasLevel = 'low' | 'mid' | 'high';

export type PanasProfile = {
  key: string;
  emoji: string;
  name: string;
  description: string;
};

function sumItems(answers: number[], items: number[]): number {
  return items.reduce((sum, i) => sum + answers[i - 1], 0);
}

function level(score: number, lowMax: number, midMax: number): PanasLevel {
  if (score <= lowMax) return 'low';
  if (score <= midMax) return 'mid';
  return 'high';
}

export function calculateScores(answers: number[]) {
  const pa = sumItems(answers, PA_ITEMS);
  const na = sumItems(answers, NA_ITEMS);
  return {
    pa,
    na,
    paLevel: level(pa, 25, 35),
    naLevel: level(na, 20, 30),
  };
}

